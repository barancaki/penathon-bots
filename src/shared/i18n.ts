export type Language = 'tr' | 'en';
export function translate(
  language: Language,
  key: string,
  params: Record<string, string | number> = {},
): string {
  const dictionary: Record<string, string> = language === 'tr' ? tr : en;
  // Own-property checks keep names like "constructor" from resolving to Object.prototype members.
  const text = Object.hasOwn(dictionary, key) ? dictionary[key] : key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  );
}
